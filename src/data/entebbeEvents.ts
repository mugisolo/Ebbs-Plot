// Official Entebbe Municipal Peninsula Geo-Fence Parameters
export const ENTEBBE_GEO_FENCE = {
  centerLat: 0.0512,
  centerLng: 32.4637,
  maxRadiusKm: 12.0, // Strict 12km Entebbe Peninsula & Katabi boundary
  minLat: 0.0100,
  maxLat: 0.1200,
  minLng: 32.4100,
  maxLng: 32.5100,
  allowedParishes: [
    'Kitoro',
    'Bugonga',
    'Nakiwogo',
    'Botanical Beach',
    'Aero Beach',
    'Waterfront',
    'Central Entebbe',
    'Lugard Avenue',
    'Manyago',
    'Katabi',
    'Abaita Ababiri',
    'Lunnyo',
  ],
};

/**
 * Haversine distance (km) from any coordinate to Entebbe Town Center (0.0512° N, 32.4637° E)
 */
export function calculateDistanceToEntebbeKm(lat: number, lng: number): number {
  const R = 6371; // Earth radius in km
  const dLat = ((lat - ENTEBBE_GEO_FENCE.centerLat) * Math.PI) / 180;
  const dLng = ((lng - ENTEBBE_GEO_FENCE.centerLng) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((ENTEBBE_GEO_FENCE.centerLat * Math.PI) / 180) *
      Math.cos((lat * Math.PI) / 180) *
      Math.sin(dLng / 2) *
      Math.sin(dLng / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Number((R * c).toFixed(2));
}

/**
 * Validates whether a GPS coordinate lies inside the Entebbe Municipal Geo-Lock
 */
export function isWithinEntebbeBounds(lat: number, lng: number): boolean {
  const dist = calculateDistanceToEntebbeKm(lat, lng);
  const inBox =
    lat >= ENTEBBE_GEO_FENCE.minLat &&
    lat <= ENTEBBE_GEO_FENCE.maxLat &&
    lng >= ENTEBBE_GEO_FENCE.minLng &&
    lng <= ENTEBBE_GEO_FENCE.maxLng;
  return inBox && dist <= ENTEBBE_GEO_FENCE.maxRadiusKm;
}

